/** Normalized, validated equity quote as cached and served. */
export interface NormalizedEquityQuote {
  symbol: string;
  companyName: string;
  /** Last price in NGN as supplied by the provider; null when unavailable. */
  lastPriceNgn: number | null;
  /** Provider-supplied daily percentage change; null when unavailable. Never computed. */
  dailyChangePercent: number | null;
  /** Provider quote timestamp (`last_updated`), ISO-8601; null when unavailable. */
  quoteTimestamp: string | null;
  available: boolean;
  unavailableReason: EquityUnavailableReason | null;
}

/**
 * Why one equity is unavailable. `INVALID_PROVIDER_DATA` is retained for
 * backward compatibility; new values are additive. Consumers must treat any
 * unknown value as a generic "unavailable".
 */
export type EquityUnavailableReason =
  | 'NOT_IN_PROVIDER_RESPONSE'
  | 'INVALID_PROVIDER_DATA'
  | 'DUPLICATE_IN_PROVIDER_RESPONSE'
  | 'MISSING_QUOTE_TIMESTAMP'
  | 'INVALID_QUOTE_TIMESTAMP'
  | 'FUTURE_QUOTE_TIMESTAMP'
  | 'INVALID_PRICE'
  | 'QUOTE_EXPIRED';

/** Equity as served publicly: the cached quote plus its age at response time. */
export interface PublicEquityQuote extends NormalizedEquityQuote {
  /** Seconds between `quoteTimestamp` and `generatedAt`; null when unavailable. */
  quoteAgeSeconds: number | null;
}

/**
 * NGX summary indicators exactly as supplied by `/market/snapshot` (latest
 * available trading day). Never derived from equities. Market-capitalisation
 * values are passed through as supplied; the provider does not document their
 * unit, so they must be verified against a live response before display.
 */
export interface MarketSummary {
  /** Provider trading date (YYYY-MM-DD). */
  tradingDate: string;
  allShareIndex: number | null;
  allShareIndexChange: number | null;
  allShareIndexChangePercent: number | null;
  equityMarketCapitalisation: number | null;
  totalMarketCapitalisation: number | null;
  /** Provider `updated_at` (ISO-8601) or null if not supplied/valid. */
  providerUpdatedAt: string | null;
}

/** Provider quota metadata (from the response envelope `meta`). */
export interface ProviderQuotaMeta {
  callsRemaining: number | null;
  resetAt: string | null;
}

/** Cached document stored in Redis under `sf:market-data:v1:snapshot`. */
export interface CachedMarketSnapshot {
  schemaVersion: 1;
  equities: {
    /** When Starfetch last successfully refreshed the equities from the provider. */
    refreshedAt: string;
    items: NormalizedEquityQuote[];
  };
  summary: {
    /** When Starfetch last successfully refreshed the summary from the provider. */
    refreshedAt: string;
    data: MarketSummary;
  } | null;
}

export type PublicSnapshotStatus = 'ok' | 'stale';
export type StaleReason = 'REFRESH_IN_PROGRESS' | 'REFRESH_FAILED' | 'REFRESH_PAUSED';
export type UnavailableReason =
  | 'REFRESH_IN_PROGRESS'
  | 'REFRESH_FAILED'
  | 'REFRESH_PAUSED'
  | 'CACHE_UNAVAILABLE'
  | 'QUOTES_EXPIRED';

/** Public contract for `GET /api/v1/public/market-snapshot` (inside the `data` envelope). */
export interface PublicMarketSnapshot {
  status: PublicSnapshotStatus;
  provider: { name: string; url: string; attribution: string };
  dataType: 'delayed';
  delayNotice: string;
  cache: {
    /** When Starfetch last refreshed equities from the provider (NOT the quote time). */
    refreshedAt: string;
    ageSeconds: number;
    refreshIntervalSeconds: number;
    nextRefreshDueAt: string;
    isStale: boolean;
    staleReason: StaleReason | null;
  };
  equities: PublicEquityQuote[];
  /** Provider summary with its own Starfetch refresh time; null when the provider supplied none. */
  marketSummary: (MarketSummary & { refreshedAt: string; isStale: boolean }) | null;
  /** When this response was generated by the server. */
  generatedAt: string;
}
